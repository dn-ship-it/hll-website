// Builds src/components/reach-map/reach-map-engagements.js from a website
// handoff folder, so the map always shows the published engagement set.
//
//   node scripts/build-reach-map-data.mjs ~/Downloads/HLL-web-handoff-20261017
//
// Reads 02-engagements/<id>/content.json only. Where each engagement sits
// on the map is decided in reach-map-places.js, not here.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const handoff = process.argv[2];
if (!handoff) {
  console.error('usage: node scripts/build-reach-map-data.mjs <handoff-folder>');
  process.exit(1);
}
const root = path.join(handoff, '02-engagements');
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '../src/components/reach-map/reach-map-engagements.js');

function titleOf(c) {
  const title = (c.engagement || '').split(':')[0].trim();
  const name = (c.shown_as || c.name || '').toLowerCase();
  return title && !name.includes(title.toLowerCase()) && !title.toLowerCase().includes(name) ? title : null;
}

const rows = fs.readdirSync(root)
  .filter((id) => fs.existsSync(path.join(root, id, 'content.json')))
  .map((id) => {
    const c = JSON.parse(fs.readFileSync(path.join(root, id, 'content.json'), 'utf8'));
    if (c.publish_on_site !== 'Yes') return null;
    const outcome = (c.outcomes || []).find((o) => o.figure) || null;
    return {
      id: c.id,
      name: c.shown_as || c.name,
      // The engagement's own title, when it says more than the client name.
      title: titleOf(c),
      service: c.service,
      serviceId: c.service_id,
      industry: c.industry_child || c.industry,
      years: c.years,
      location: c.location,
      outcome: outcome ? { figure: outcome.figure, text: outcome.text } : null,
      hasLogo: fs.existsSync(path.join(root, id, 'logo.png')),
      href: c.url_path,
    };
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name));

fs.writeFileSync(out, `// Generated by scripts/build-reach-map-data.mjs from ${path.basename(handoff)}.
// Do not hand-edit: change the engagement ledger, rebuild the handoff, rerun.
export const ENGAGEMENTS = ${JSON.stringify(rows, null, 2)};
`);
console.log(`${rows.length} engagements -> ${path.relative(process.cwd(), out)}`);
